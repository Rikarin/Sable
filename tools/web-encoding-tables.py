#!/usr/bin/env python3
"""Writes what Sable.Text's web escaping (TextEncoder, Html) is made from:

    tools/web-encoding-tables.py [entities.json] [Blocks.txt]

- lib/Sable.Text/HtmlEntities.sb, the WHATWG HTML standard's named
  character references, from https://html.spec.whatwg.org/entities.json;
- lib/Sable.Text/UnicodeRange+Blocks.sb, a UnicodeRange for each block of
  the Basic Multilingual Plane but the surrogates and private use (as .NET's
  UnicodeRanges has them), from Blocks.txt of
  https://www.unicode.org/Public/<version>/ucd/;
- tests/lib/Sable.Text/UnicodeBlocks.sb, every one of those ranges, in a
  list the tests check them by.

Neither file is committed: by default they are read from tools/html/ and
tools/unicode/ (downloaded by hand). They are data, read and never run.

The named references are a table of fixed-width records, RECORDS_PER_LINE to
a line, so record r starts at byte r * width + r / RECORDS_PER_LINE; their
names, without the '&' and the ';', are a pool of their own, NAMES_PER_LINE
bytes to a line. A record holds, in base-32 digits '0' (0) to 'O' (31):
where its name starts in the pool (4 digits), how long it is (1), whether
it is also a reference without its ';' (1: the legacy ones), and its one or
two code points (5 each, the second 0 when there is none). Records are in
the order of their names' bytes, so a name is found by bisection.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ENTITIES = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tools" / "html" / "entities.json"
BLOCKS = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "tools" / "unicode" / "Blocks.txt"
UNICODE_VERSION = "16.0.0"
DIGITS = "".join(chr(0x30 + i) for i in range(32))  # '0'..'O'
RECORDS_PER_LINE = 8
NAMES_PER_LINE = 128
EXCLUDED_BLOCKS = {"High Surrogates", "High Private Use Surrogates", "Low Surrogates", "Private Use Area"}


def digits(value, width):
    if value < 0 or value >= 32 ** width:
        raise ValueError(f"{value} does not fit {width} base-32 digits")
    out = []
    for _ in range(width):
        out.append(DIGITS[value % 32])
        value //= 32
    return "".join(reversed(out))


def lines(text, width):
    return "\n".join("    " + text[i:i + width] for i in range(0, len(text), width))


def entities():
    table = json.loads(ENTITIES.read_text(encoding="utf-8"))
    names = {}
    for key, value in table.items():
        if not re.fullmatch(r"&[A-Za-z0-9]+;?", key):
            raise ValueError(f"an unexpected name {key!r}")
        name = key[1:].rstrip(";")
        points = value["codepoints"]
        if len(points) not in (1, 2) or len(name) > 31:
            raise ValueError(f"{key!r} does not fit a record")
        entry = names.setdefault(name, {"points": points, "legacy": False, "terminated": False})
        if entry["points"] != points:
            raise ValueError(f"{name!r} stands for two things")
        if key.endswith(";"):
            entry["terminated"] = True
        else:
            entry["legacy"] = True
    pool = ""
    records = []
    for name in sorted(names, key=lambda n: n.encode("ascii")):
        entry = names[name]
        if not entry["terminated"]:
            raise ValueError(f"{name!r} has no form with ';'")
        points = entry["points"] + [0]
        records.append(digits(len(pool), 4) + digits(len(name), 1) + ("1" if entry["legacy"] else "0")
                       + digits(points[0], 5) + digits(points[1], 5))
        pool += name
    width = len(records[0])
    body = "".join(records)
    out = [
        "module Sable.Text",
        "",
        f"// Generated by tools/web-encoding-tables.py from the WHATWG HTML standard's",
        "// entities.json: do not edit; see there for the format.",
        "",
        f"const htmlEntityRecordsPerLine = {RECORDS_PER_LINE}",
        f"const htmlEntityNamesPerLine = {NAMES_PER_LINE}",
        f"const htmlEntityRecordWidth = {width}",
        "",
        f"// The named character references, {len(records)} records of {width} digits.",
        f"const htmlEntityCount = {len(records)}",
        'const htmlEntityTable = """',
        lines(body, width * RECORDS_PER_LINE),
        '    """',
        "",
        "// Their names, without '&' or ';', one after another.",
        'const htmlEntityNames = """',
        lines(pool, NAMES_PER_LINE),
        '    """',
        "",
    ]
    (ROOT / "lib" / "Sable.Text" / "HtmlEntities.sb").write_text("\n".join(out), encoding="utf-8")


def identifier(block):
    words = [w for w in re.split(r"[ \-_]", block) if w]
    first = words[0].lower() if words[0].isupper() or words[0] == "NKo" else words[0][0].lower() + words[0][1:]
    rest = [w.capitalize() if w.isupper() else w[0].upper() + w[1:] for w in words[1:]]
    return first + "".join(rest)


def blocks():
    found = []
    for line in BLOCKS.read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        span, name = (part.strip() for part in line.split(";"))
        first, last = (int(x, 16) for x in span.split(".."))
        if last <= 0xFFFF and name not in EXCLUDED_BLOCKS:
            found.append((first, last, name, identifier(name)))
    out = [
        "module Sable.Text",
        "",
        f"// Generated by tools/web-encoding-tables.py from Unicode {UNICODE_VERSION}'s",
        "// Blocks.txt: do not edit.",
        "",
        "extension UnicodeRange {",
    ]
    for first, last, name, ident in found:
        out.append(f"    /// U+{first:04X} to U+{last:04X}: {name}.")
        out.append(f"    public static var {ident}: UnicodeRange => UnicodeRange(first: 0x{first:04X}, length: 0x{last - first + 1:X})")
    out.append("}")
    out.append("")
    (ROOT / "lib" / "Sable.Text" / "UnicodeRange+Blocks.sb").write_text("\n".join(out), encoding="utf-8")
    test = [
        "module UnicodeBlocks",
        "",
        "// Generated by tools/web-encoding-tables.py: do not edit.",
        "",
        "import Sable.Text",
        "",
        "/// Every named block, in order, with its name in Blocks.txt.",
        "public fn everyUnicodeBlock() -> (String, UnicodeRange)[>..] {",
        "    return [",
    ]
    for first, last, name, ident in found:
        test.append(f'        ("{name}", UnicodeRange.{ident}),')
    test += ["    ]", "}", ""]
    (ROOT / "tests" / "lib" / "Sable.Text" / "UnicodeBlocks.sb").write_text("\n".join(test), encoding="utf-8")


entities()
blocks()
