// Writes tests/lib/Sable.Time/PatternTableTests.sb: what .NET's
// DateTimeOffset.ToString(pattern, CultureInfo.InvariantCulture) writes for
// each pattern and moment below, for Sable.Time's format(pattern:) to match.
//
//   dotnet run tools/time/dotnet-patterns.cs
//
// Run it with the .NET SDK the repository builds with (.NET 11), from the
// repository's root, and commit the table it writes. A pattern .NET refuses
// (FormatException) is left out.
using System.Globalization;
using System.Text;

var moments = new (int Year, int Month, int Day, int Hour, int Minute, int Second, int Ticks, int OffsetMinutes)[] {
    (2026, 11, 17, 9, 5, 3, 1234567, 60),
    (2005, 1, 2, 0, 0, 0, 0, -300),
    (1999, 12, 31, 23, 59, 59, 9990000, 330),
    (2024, 2, 29, 12, 30, 7, 500000, 0),
    (987, 7, 4, 13, 4, 5, 1, -570),
    (2010, 10, 10, 10, 10, 10, 1000000, 765),
};

var patterns = new[] {
    // The standard formats.
    "d", "D", "f", "F", "g", "G", "m", "M", "o", "O", "r", "R", "s", "t", "T", "u", "y", "Y",
    // Each custom specifier, at each length.
    "%d", "dd", "ddd", "dddd", "ddddd",
    "%M", "MM", "MMM", "MMMM", "MMMMM",
    "%y", "yy", "yyy", "yyyy", "yyyyy",
    "%h", "hh", "hhh", "%H", "HH", "HHH",
    "%m", "mm", "mmm", "%s", "ss", "sss",
    "%f", "ff", "fff", "ffff", "fffff", "ffffff", "fffffff",
    "%F", "FF", "FFF", "FFFF", "FFFFF", "FFFFFF", "FFFFFFF",
    "%t", "tt", "ttt", "%g", "gg",
    "%z", "zz", "zzz", "zzzz", "%K", "KK",
    // Together, with separators, quotes and escapes.
    "yyyy-MM-dd", "yyyy-MM-ddTHH:mm:ss", "yyyy-MM-dd'T'HH:mm:ss.fffK", "yyyy-MM-dd HH:mm:ss.FFFFFFF zzz",
    "dd/MM/yyyy", "MM/dd/yy", "d.M.yyyy", "dddd, MMMM d, yyyy", "ddd, d MMM yyyy", "MMM d, yyyy h:mm tt",
    "h:mm:ss.ff t", "HH:mm:ss.FFF", "HH:mm:ss.FFF'Z'", "ss.F", "ss.FF", "'Week of' MMMM d",
    "\"quoted\" yyyy", "\\d\\a\\y d", "yyyy'\\''MM", "HH\\hmm", "%d%M", "dMyy", "yyyyMMddHHmmss",
    "g yyyy", "dd MMM yyyy HH:mm:ss zzz", "hh:mm tt zz", "K yyyy", "yy-M-d H:m:s", "[yyyy]",
    "MMMM yyyy", "dddd", "hh 'o''clock' tt", "yyyy-MM-ddTHH:mm:ss.fffffffzzz", "yyyy/MM/dd",
};

var output = new StringBuilder();
output.Append("""
    module TimePatternTableTests

    // What .NET 11's DateTimeOffset.ToString(pattern, CultureInfo.InvariantCulture)
    // writes, against OffsetDateTime.format(pattern:). Generated by
    // tools/time/dotnet-patterns.cs: do not edit; run it again.

    import Sable.Testing
    import Sable.Time

    struct PatternCase {
        let moment: Int
        let pattern: String
        let expected: String
    }

    fn moment(_ index: Int) -> OffsetDateTime {
        return match index {

    """);
for (var i = 0; i < moments.Length; i++) {
    var m = moments[i];
    output.Append($"        case {i} => OffsetDateTime.of(year: {m.Year}, month: {m.Month}, day: {m.Day}, hour: {m.Hour}, minute: {m.Minute}, second: {m.Second}, nanosecond: {m.Ticks * 100}, offset: UtcOffset.of(seconds: {m.OffsetMinutes * 60})!)!\n");
}
output.Append("        case _ => OffsetDateTime.of(year: 1970, month: 1, day: 1, offset: UtcOffset.utc)!\n    }\n}\n\n");
output.Append("fn cases() -> PatternCase[>..] {\n    return [\n");
var count = 0;
for (var i = 0; i < moments.Length; i++) {
    var m = moments[i];
    var moment = new DateTimeOffset(m.Year, m.Month, m.Day, m.Hour, m.Minute, m.Second, TimeSpan.FromMinutes(m.OffsetMinutes)).AddTicks(m.Ticks);
    foreach (var pattern in patterns) {
        string expected;
        try {
            expected = moment.ToString(pattern, CultureInfo.InvariantCulture);
        } catch (FormatException) {
            continue;
        }
        output.Append($"        PatternCase {{ moment: {i}, pattern: {Quote(pattern)}, expected: {Quote(expected)} }},\n");
        count++;
    }
}
output.Append("    ]\n}\n\n");
output.Append($$"""
    @test
    fn everyPatternWritesWhatDotNetWrites() {
        let all = cases()
        assertEqual(all.count, {{count}})
        for c in all {
            let written = moment(c.moment).format(pattern: c.pattern)
            assert(written == c.expected, "pattern \(c.pattern) of moment \(c.moment): \(written), not \(c.expected)")
        }
    }

    """);
File.WriteAllText("tests/lib/Sable.Time/PatternTableTests.sb", output.ToString());
Console.WriteLine($"{count} cases");

static string Quote(string text) {
    var quoted = new StringBuilder("\"");
    foreach (var c in text) {
        quoted.Append(c switch {
            '"' => "\\\"",
            '\\' => "\\\\",
            _ => c.ToString(),
        });
    }
    return quoted.Append('"').ToString();
}
