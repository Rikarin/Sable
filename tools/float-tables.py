#!/usr/bin/env python3
"""Writes runtime/number_tables.h: the powers of ten runtime/numbers.c writes
and reads floats with.

    tools/float-tables.py            # write the file
    tools/float-tables.py --check    # fail if it is not what would be written

The entry for 10^k is its first 128 bits, rounded up: the g of

    10^k <= g * 2^r, 2^127 <= g < 2^128

for the r that is floor(log2(10^k)) - 127. It is exact for k from 0 to 55, where
5^k fits in 128 bits. Integer arithmetic throughout.
"""

import sys
from pathlib import Path

LEAST, GREATEST = -342, 324


def entry(k):
    if k >= 0:
        power = 10**k
        shift = power.bit_length() - 128
        return -(-power >> shift) if shift > 0 else power << -shift
    power = 10**-k
    # The ceiling of 2^n / power is of 128 bits for one n: power is no power of two.
    n = 127 + power.bit_length()
    g = -(-(1 << n) // power)
    assert g.bit_length() == 128
    return g


def generate():
    lines = [
        "// Generated by tools/float-tables.py; do not edit. The first 128 bits of 10^k,",
        "// rounded up, high half first, for k from POWER_LEAST to POWER_GREATEST.",
        "",
        f"#define POWER_LEAST ({LEAST})",
        f"#define POWER_GREATEST {GREATEST}",
        "",
        f"static const uint64_t powers_of_ten[{GREATEST - LEAST + 1}][2] = {{",
    ]
    for k in range(LEAST, GREATEST + 1):
        g = entry(k)
        lines.append(f"    {{ 0x{g >> 64:016x}u, 0x{g & (1 << 64) - 1:016x}u }},")
    return "\n".join([*lines, "};", ""])


def main():
    path = Path(__file__).resolve().parent.parent / "runtime/number_tables.h"
    text = generate()
    if sys.argv[1:] == ["--check"]:
        if path.read_text() != text:
            sys.exit(f"{path} is not what tools/float-tables.py writes")
    else:
        path.write_text(text)


if __name__ == "__main__":
    main()
