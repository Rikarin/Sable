#!/usr/bin/env python3
"""Makes lib/Sable.IO.Compression/BrotliDictionary.sb, the data RFC 7932 gives:

    tools/brotli-dictionary.py rfc7932.txt

with the RFC's text from https://www.rfc-editor.org/rfc/rfc7932.txt. The file
has, as Base64 of raw deflate, what BrotliTables.sb reads: the static
dictionary's 122784 bytes (Appendix A), the 121 transforms as the RFC's own
check of them has them, 648 bytes (Appendix B), and the three tables of 256
bytes that context IDs are worked out by (section 7.1). Each part's checksum is
the RFC's, or nothing is written.
"""

import base64
import pathlib
import re
import sys
import zlib

TRANSFORMS = {"Identity": 0, "FermentFirst": 1, "FermentAll": 2}
TRANSFORMS |= {f"OmitFirst{n}": 2 + n for n in range(1, 10)}
TRANSFORMS |= {f"OmitLast{n}": 11 + n for n in range(1, 10)}


def unescape(text):
    return text.encode().decode("unicode_escape").encode("latin-1")


def check(name, data, length, crc):
    if len(data) != length or zlib.crc32(data) != crc:
        sys.exit(f"{name}: {len(data)} bytes with the CRC-32 {zlib.crc32(data):08x}")
    return data


def main():
    text = pathlib.Path(sys.argv[1]).read_text()
    start = text.index("Appendix A.  Static Dictionary Data")
    transforms_at = text.index("Appendix B.  List of Word Transformations", start)
    words = "".join(re.findall(r"^ {6}([0-9a-f]+)$", text[start:transforms_at], re.M))
    dictionary = check("dictionary", bytes.fromhex(words), 122784, 0x5136CB04)

    end = text.index("Appendix C.  Computing CRC-32 Check Values", transforms_at)
    rows = re.findall(r'^ +(\d+) +"((?:[^"\\]|\\.)*)" +(\w+) +"((?:[^"\\]|\\.)*)"$', text[transforms_at:end], re.M)
    if [int(row[0]) for row in rows] != list(range(121)):
        sys.exit(f"{len(rows)} transforms")
    transforms = b"".join(unescape(prefix) + b"\0" + bytes([TRANSFORMS[kind]]) + unescape(suffix) + b"\0" for _, prefix, kind, suffix in rows)
    check("transforms", transforms, 648, 0x3D965F81)

    tables = b""
    for number, crc in ((0, 0x8E91EFB7), (1, 0xD01A32F4), (2, 0x0DD7A0D6)):
        at = text.index(f"Lut{number} :=")
        rows = []
        for line in text[at:].split("\n")[1:]:
            if re.fullmatch(r"[ \d,]*\d,?", line) and "," in line:
                rows += [int(value) for value in re.findall(r"\d+", line)]
            if len(rows) == 256:
                break
        tables += check(f"Lut{number}", bytes(rows), 256, crc)

    packer = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    packed = packer.compress(dictionary + transforms + tables) + packer.flush()
    digits = base64.b64encode(packed).decode()
    lines = "\n".join("    " + digits[i:i + 116] for i in range(0, len(digits), 116))
    target = pathlib.Path(__file__).resolve().parents[1] / "lib/Sable.IO.Compression/BrotliDictionary.sb"
    target.write_text(f'''module Sable.IO.Compression

// Generated by tools/brotli-dictionary.py from RFC 7932; do not edit.

/// Brotli's static dictionary, 122784 bytes, its transforms, 648, and its three
/// tables of contexts, 256 each: raw deflate, in Base64.
const brotliData = """
{lines}
"""
''')


main()
