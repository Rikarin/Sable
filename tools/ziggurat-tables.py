#!/usr/bin/env python3
"""Writes lib/Sable.Math/ZigguratTables.sb: the layers NormalDistribution and
ExponentialDistribution draw from.

    tools/ziggurat-tables.py            # write the file
    tools/ziggurat-tables.py --check    # fail if it is not what would be written

A ziggurat covers the area under a density f, f(0) = 1, with 256 layers of one
area v. The base is the rectangle out to x = r together with the tail beyond
it; the layers above are rectangles, the topmost closing at f(0). So r is the
root of one equation, found here by bisection in 80 digits of decimal
arithmetic, and the tables are, each entry rounded once to the nearest F64:

    x[0] = v / f(r), x[1] = r, ..., x[255], x[256] = 0    layer i is x[i] wide
    f[i] = f(x[i])                                        and from f[i] to f[i + 1]

(x[0] is the width the base would have as a rectangle of height f(r).) Python's
standard library is all it uses.
"""

import sys
from decimal import Decimal, getcontext
from pathlib import Path

getcontext().prec = 80
LAYERS = 256


def pi():
    """By the Gauss-Legendre iteration."""
    a, b, t, p = Decimal(1), 1 / Decimal(2).sqrt(), Decimal("0.25"), Decimal(1)
    for _ in range(8):
        a, b, t, p = (a + b) / 2, (a * b).sqrt(), t - p * ((a - b) / 2) ** 2, 2 * p
    return (a + b) ** 2 / (4 * t)


HALF_AREA = (pi() / 2).sqrt()


class Normal:
    name = "normal"
    bracket = ("3", "4")

    @staticmethod
    def density(x):
        return (-x * x / 2).exp()

    @staticmethod
    def inverse(y):
        return (-2 * y.ln()).sqrt()

    @staticmethod
    def tail(x):
        # The area up to x is exp(-x^2/2) times the sum of x^(2k+1) / (2k+1)!!.
        term = total = x
        k = 1
        while term > Decimal(10) ** -90:
            term = term * x * x / (2 * k + 1)
            total += term
            k += 1
        return HALF_AREA - total * Normal.density(x)


class Exponential:
    name = "exponential"
    bracket = ("7", "8")

    @staticmethod
    def density(x):
        return (-x).exp()

    @staticmethod
    def inverse(y):
        return -y.ln()

    @staticmethod
    def tail(x):
        return (-x).exp()


def layers(shape, r):
    """The layers' widths for a base out to r, and how far above f(0) the last ends (None: above it too soon)."""
    v = r * shape.density(r) + shape.tail(r)
    xs = [v / shape.density(r), r]
    while len(xs) < LAYERS:
        y = v / xs[-1] + shape.density(xs[-1])
        if y >= 1:
            return xs, None
        xs.append(shape.inverse(y))
    return xs, v / xs[-1] + shape.density(xs[-1]) - 1


def solve(shape):
    """A wider base has a smaller area, and a ziggurat that closes lower."""
    low, high = (Decimal(x) for x in shape.bracket)
    while high - low > Decimal(10) ** -60:
        middle = (low + high) / 2
        _, over = layers(shape, middle)
        if over is None or over > 0:
            low = middle
        else:
            high = middle
    xs, over = layers(shape, high)
    assert abs(over) < Decimal(10) ** -50
    return xs + [Decimal(0)]


def table(name, values):
    lines, line = [], "   "
    for value in values:
        text = f" {float(value)!r},"
        if len(line) + len(text) > 100:
            lines.append(line)
            line = "   "
        line += text
    lines.append(line.rstrip(","))
    return f"const {name}: F64[{len(values)}] = [\n" + "\n".join(lines) + "\n]\n"


def generate():
    parts = [
        "module Sable.Math\n\n"
        "// Generated by tools/ziggurat-tables.py; do not edit. The layers of the\n"
        "// ziggurats of the normal and the exponential distribution: entry i of a\n"
        "// 'Widths' table is the width of layer i, and of its 'Heights' table the\n"
        "// density there. Each is the nearest F64 to the exact value.\n"
    ]
    for shape in (Normal, Exponential):
        xs = solve(shape)
        parts.append(table(f"{shape.name}Widths", xs))
        parts.append(table(f"{shape.name}Heights", [shape.density(x) for x in xs]))
    return "\n".join(parts)


def main():
    path = Path(__file__).resolve().parent.parent / "lib/Sable.Math/ZigguratTables.sb"
    text = generate()
    if sys.argv[1:] == ["--check"]:
        if path.read_text() != text:
            sys.exit(f"{path} is not what tools/ziggurat-tables.py writes")
    else:
        path.write_text(text)


if __name__ == "__main__":
    main()
